    def test_outputs_are_lf_and_end_with_newline(self):
        for path, content in self.outputs.items():
            self.assertNotIn("\r", content, path)
            self.assertTrue(content.endswith("\n"), path)
            self.assertFalse(content.endswith("\n\n"), path)



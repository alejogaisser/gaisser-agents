        self.assertEqual(code, 0, out + err)
        self.assertIn("installed", out)
        for a in ("architect", "coder", "tester"):
            self.assertSameAsDist(base / (".claude/agents/%s.md" % a),
                                  REPO / ("dist/claude-code/dev-pipeline/agents/%s.md" % a))
        self.assertSameAsDist(base / ".claude/skills/pipeline/SKILL.md",
                              REPO / "dist/claude-code/dev-pipeline/skills/pipeline/SKILL.md")
        # rerun -> unchanged
        code, out, err = self.run_install("claude", "install")
        self.assertEqual(code, 0, out + err)
        self.assertEqual(out.count("[unchanged]"), 4, out)
        self.assertNotIn("[installed]", out)
        # edit -> skipped, then force -> overwritten + backup
        target = base / ".claude/agents/coder.md"
        original = target.read_bytes()
        target.write_bytes(original + b"\nlocal edit\n")
        code, out, err = self.run_install("claude", "install")
        self.assertEqual(code, 0, out + err)
        self.assertIn("[skipped]", out)
        self.assertEqual(target.read_bytes(), original + b"\nlocal edit\n")
        code, out, err = self.run_install("claude", "force")
        self.assertEqual(code, 0, out + err)
        self.assertIn("overwritten", out)
        self.assertEqual(target.read_bytes(), original)
        backups = list((base / ".claude/agent-catalog-backups").rglob("coder.md"))
        self.assertEqual(len(backups), 1, out)
        self.assertEqual(backups[0].read_bytes(), original + b"\nlocal edit\n")
        # backups are not inside agents/ or skills/
        self.assertFalse(any("backup" in p for p in self.files(base / ".claude/agents")))


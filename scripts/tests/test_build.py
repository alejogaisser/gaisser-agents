def sh_path(p):
    """Windows path to a form Git Bash accepts."""
    p = str(p).replace("\\", "/")
    if len(p) > 1 and p[1] == ":":
        p = "/" + p[0].lower() + p[2:]
    return p


class InstallBase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.mkdtemp(prefix="ga install ")  # contains a space on purpose
        self.addCleanup(_rmtree, self._tmp)
        self.base = Path(self._tmp) / "my base"
        self.base.mkdir()

    # subclasses implement run(*args) -> (code, out, err)
    def files(self, root):
        return sorted(p.relative_to(root).as_posix() for p in Path(root).rglob("*") if p.is_file())

    def assertSameAsDist(self, installed, dist):
        self.assertEqual(Path(installed).read_bytes(), Path(dist).read_bytes())

    def common_cases(self):
        base = self.base
        # claude install
        code, out, err = self.run_install("claude", "install")
        self.assertEqual(code, 0, out + err)
        self.assertIn("installed", out)
        for a in AGENTS:
            self.assertSameAsDist(base / (".claude/agents/%s.md" % a),
                                  REPO / ("dist/claude-code/gaisser-agents/agents/%s.md" % a))
        self.assertSameAsDist(base / ".claude/skills/dev-team/SKILL.md",
                              REPO / "dist/claude-code/gaisser-agents/skills/dev-team/SKILL.md")
        # rerun -> unchanged
        code, out, err = self.run_install("claude", "install")
        self.assertEqual(code, 0, out + err)
        self.assertEqual(out.count("[unchanged]"), 4, out)
        self.assertNotIn("[installed]", out)
        # edit -> skipped, then force -> overwritten + backup
        target = base / ".claude/agents/dev-coder.md"
        original = target.read_bytes()
        target.write_bytes(original + b"\nlocal edit\n")
        code, out, err = self.run_install("claude", "install")
        self.assertEqual(code, 0, out + err)
        self.assertIn("[skipped]", out)
        self.assertEqual(target.read_bytes(), original + b"\nlocal edit\n")
        code, out, err = self.run_install("claude", "force")
        self.assertEqual(code, 0, out + err)
        self.assertIn("overwritten", out)
        self.assertEqual(target.read_bytes(), original)
        backups = list((base / ".claude/agent-catalog-backups").rglob("dev-coder.md"))
        self.assertEqual(len(backups), 1, out)
        self.assertEqual(backups[0].read_bytes(), original + b"\nlocal edit\n")
        # backups are not inside agents/ or skills/
        self.assertFalse(any("backup" in p for p in self.files(base / ".claude/agents")))

    def codex_cases(self):
        base = self.base
        code, out, err = self.run_install("codex", "install")
        self.assertEqual(code, 0, out + err)
        for a in AGENTS:
            self.assertSameAsDist(base / (".codex/agents/%s.toml" % a),
                                  REPO / ("dist/codex/gaisser-agents/agents/%s.toml" % a))
        self.assertSameAsDist(base / ".agents/skills/dev-team/SKILL.md",
                              REPO / "dist/codex/gaisser-agents/skills/dev-team/SKILL.md")

    def agents_only_cases(self):
        code, out, err = self.run_install("codex", "agents-only")
        self.assertEqual(code, 0, out + err)
        self.assertEqual(len(list((self.base / ".codex/agents").glob("*.toml"))), 3)
        self.assertFalse((self.base / ".agents").exists(), self.files(self.base))
        self.assertNotIn("skills/", out)
        # agents-only has no effect on the claude target
        code, out, err = self.run_install("claude", "agents-only")
        self.assertEqual(code, 0, out + err)
        self.assertTrue((self.base / ".claude/skills/dev-team/SKILL.md").is_file())

    def dry_run_cases(self):
        code, out, err = self.run_install("all", "dry-run")
        self.assertEqual(code, 0, out + err)
        self.assertIn("[dry-run]", out)
        self.assertEqual(self.files(self.base), [])

    def error_cases(self):
        code, out, err = self.run_install("claude", "bad-plugin")
        self.assertEqual(code, 2, out + err)
        code, out, err = self.run_install("claude", "no-selection")
        self.assertEqual(code, 2, out + err)

    def list_cases(self):
        code, out, err = self.run_install("all", "list")
        self.assertEqual(code, 0, out + err)
        self.assertRegex(out, r"\[claude\] gaisser-agents\s+agents: dev-architect, dev-coder, dev-tester\s+skills: dev-team")
        self.assertRegex(out, r"\[codex\] gaisser-agents\s+agents: dev-architect, dev-coder, dev-tester\s+skills: dev-team")
        self.assertEqual(self.files(self.base), [])



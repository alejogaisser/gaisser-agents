class VersionBumpTest(TempRepoCase):
    def git(self, *args):
        r = subprocess.run(["git", *GIT_ID, *args], cwd=str(self.root),
                           capture_output=True, text=True, encoding="utf-8")
        self.assertEqual(r.returncode, 0, r.stderr)
        return r.stdout

    def setUp(self):
        super().setUp()
        self.git("init", "-q", "-b", "main")
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "base")

    def change_prompt_and_build(self):
        self.edit_text("teams/dev-team/agents/dev-coder/prompt.md", lambda t: t.replace("implement exactly", "implement precisely"))
        self.assertEqual(build.main(["--root", str(self.root)]), 0)
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "change")

    def test_change_without_bump_errors(self):
        self.change_prompt_and_build()
        f = build.check_version_bumps(self.root, "HEAD~1")
        self.assertTrue(has_error(f, "plugin.version was not bumped", "catalog.json"), f)

    def test_change_with_bump_passes(self):
        self.edit_json("catalog.json", lambda d: d["plugin"].update(version="3.0.1"))
        self.change_prompt_and_build()
        self.assertEqual(errors_of(build.check_version_bumps(self.root, "HEAD~1")), [])

    def test_version_decrease_errors(self):
        self.edit_json("catalog.json", lambda d: d["plugin"].update(version="2.9.0"))
        self.change_prompt_and_build()
        self.assertTrue(has_error(build.check_version_bumps(self.root, "HEAD~1"),
                                  "plugin.version went down", "catalog.json"))

    def test_unknown_ref_warns(self):
        f = build.check_version_bumps(self.root, "no-such-ref")
        self.assertEqual([x.level for x in f], ["WARN"])
        self.assertIn("base ref not found", f[0].message)

    def test_not_a_git_tree_exits_2(self):
        plain = Path(self._tmp) / "plain"
        copy_repo(plain)
        self.assertEqual(build.main(["--root", str(plain), "--base-ref", "HEAD"]), 2)



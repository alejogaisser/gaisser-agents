def _rmtree(path):
    def onerr(func, p, exc):
        os.chmod(p, 0o700)
        func(p)
    shutil.rmtree(path, onerror=onerr)


def copy_repo(dest):
    """Copy the repository (without .git and caches) into dest."""
    shutil.copytree(
        REPO, dest, dirs_exist_ok=True,
        ignore=shutil.ignore_patterns(".git", "__pycache__", "tests"),
    )
    return Path(dest)


def errors_of(findings):
    return [f for f in findings if f.level == "ERROR"]


def has_error(findings, text, path=None):
    return any(
        text in f.message and (path is None or f.path == path)
        for f in errors_of(findings)
    )


def read(root, rel):
    return (Path(root) / rel).read_bytes().decode("utf-8")


class TempRepoCase(unittest.TestCase):
    """Each test gets a fresh copy of the repository in a temp folder."""

    def setUp(self):
        self._tmp = tempfile.mkdtemp(prefix="ga-test-")
        self.addCleanup(_rmtree, self._tmp)
        self.root = copy_repo(Path(self._tmp) / "repo")

    def edit_json(self, rel, fn):
        p = self.root / rel
        data = json.loads(p.read_text(encoding="utf-8"))
        fn(data)
        p.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")

    def edit_text(self, rel, fn):
        p = self.root / rel
        text = p.read_bytes().decode("utf-8")
        p.write_bytes(fn(text).encode("utf-8"))


